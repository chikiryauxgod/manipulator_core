#!/usr/bin/env python3
"""Generate the CubeIDE float32 header from the pinned kinematics template."""
from pathlib import Path

root = Path(__file__).resolve().parents[1]
template = root / "third-party/manipulator_kinematics/cmake/config.h.in"
output = root / "config/manipulator/config.h"
text = template.read_text().replace("@K_USE_FLOAT@", "1")
if "@" in text:
    raise SystemExit("Unknown CMake template variable; update this generator")
output.parent.mkdir(parents=True, exist_ok=True)
output.write_text("/* Generated by tools/generate_kinematics_config.py. Do not edit. */\n" + text)
